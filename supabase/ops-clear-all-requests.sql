-- ---------------------------------------------------------------------------
-- ขั้นที่ 2) ลบจริง — คลุมทั้งบล็อกแล้วกด Run ทีเดียว
--   ทั้งหมดอยู่ใน transaction เดียว: ถ้าพังกลางทางจะไม่ลบอะไรเลย
